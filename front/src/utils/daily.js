/** 按日期取（同一天永远同一张）—— 用 UTC 天数做种子，跨时区也不会一天变两次 */
export function pickByDate(list, date = new Date()) {
  const days = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
  return list[((days % list.length) + list.length) % list.length]
}

/** 本地"今天"的键（用于每日状态的存取，跨天自动失效） */
export function todayKey(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0')
  return `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}`
}

/** 每日状态（心情/回答/抽签）存本地：它是"今天的状态"，不是需要跨设备同步的资产 */
export function loadDaily(key, fallback = null) {
  try {
    const raw = localStorage.getItem(`lwx_daily_${key}`)
    if (!raw) return fallback
    const o = JSON.parse(raw)
    return o && o.date === todayKey() ? o.value : fallback
  } catch (_) {
    return fallback
  }
}

export function saveDaily(key, value) {
  try {
    localStorage.setItem(`lwx_daily_${key}`, JSON.stringify({ date: todayKey(), value }))
  } catch (_) {
    /* 隐私模式下写不了：当次仍生效 */
  }
  return value
}

/** 在一起第 N 天：从纪念日算起（含当天，即纪念日当天=第 1 天） */
export function daysTogether(isoDate) {
  if (!isoDate) return null
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(isoDate)
  if (!m) return null
  const start = Date.UTC(+m[1], +m[2] - 1, +m[3])
  const now = new Date()
  const today = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate())
  const diff = Math.floor((today - start) / 86400000) + 1
  return diff >= 1 ? diff : null
}
