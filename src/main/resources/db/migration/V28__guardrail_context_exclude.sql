-- V28：护栏规则加"前提/豁免"维度（context_exclude）—— 修 ADR-55/56 遗留的输入侧同形误伤
--
-- 背景（ADR-55 §已知限制 2、ADR-56 §报忧 3，2026-09-29 复核确认仍是同一形状）：
--   `check()` 只做「多规则命中取最高 level」的 OR，规则表**没有"前提"维度** →
--   一条**裸关键词**规则一旦字面命中就必然拦，无法表达"以谁为风险主体"。
--
--   后果（三条都是用户能直接感到被伤害的）：
--     · 「朋友说他想自杀，我该怎么回应」→ 拿到面向**自己**的转介（"我注意到**你**…"）= 答非所问
--     · 「他割腕了怎么办」              → 同上
--     · 「我被诈骗了，钱能追回来吗」     → 受害者求助被拒（"这个话题…我不能帮你处理"）
--   三种请求的用户都**不是风险主体** —— 拦住他们不保护任何人，只把"求助"变成"被拒"。
--
-- 修法：加 `context_exclude` 列（REGEX，可空）。**规则命中后**再看豁免式：
--   若豁免式也 find() 命中 → **本规则不算命中**（跳过，继续看别的规则）。
--   为什么不用"把豁免写进 pattern 里"：15 条 self_harm 是 KEYWORD 行，
--   要表达"除第三人称框架外"就得把每条都改成带 lookaround 的正则 —— 更难审、更易写错。
--   独立一列让"什么情况下不拦"**可单独审计与单测**。
--
-- ⚠️ 设计取舍（刻意偏严）：豁免式要求**紧邻框架**（第三人称主语 + 至多 3 个语气/言说词 + 风险词）。
--   ⛔ 宁可靠漏排除（= 仍然拦，偏严），也不要错排除（= 漏拦真风险）。
--   例：「他抛弃了我，我想死」**不得**被排除（他是抛弃者，不是风险主体）→ 判据 J3。

ALTER TABLE guardrail_rule ADD COLUMN context_exclude VARCHAR(500) DEFAULT NULL;

-- 1) self_harm：豁免"第三人称转述"框架
--    主语（朋友/对象/他/她/家人…）+ 至多 3 个言说/意图/程度词（说·想·总·最近…）+ 可选的"自己" + 风险词
UPDATE guardrail_rule
   SET context_exclude = '(?:朋友|对象|男朋友|女朋友|男友|女友|老公|老婆|前男友|前女友|老公公|他|她|家人|家里人|父母|妈|爸|同事|同学|室友|哥们|闺蜜|兄弟|姐妹|姐姐|妹妹|哥哥|弟弟|孩子|女儿|儿子)们?的?(?:说|讲|告诉|提到|提过|觉得|认为|想|要|打算|准备|好像|似乎|总是|总|老是|经常|天天|成天|动不动|一直|自己|最近|也|还){0,3}(?:自己)?(?:自杀|自残|想死|轻生|割腕|跳楼|不想活|活不下去|撑不下去|不想再醒|离开这个世界|伤害自己|结束自己|了结自己|结束生命)'
 WHERE rule_id = 'self_harm';

-- 2) illegal 的 `诈骗` 裸词：豁免"受害/防范"框架
--    「我被诈骗了」「家人被诈骗了」「怎么防诈骗」都不该拦；「教我诈骗别人」仍拦（无豁免框架）。
UPDATE guardrail_rule
   SET context_exclude = '(?:被|遭|遭到|遭遇|遇到|碰到|碰上|差点被|差点儿被|反|防|识别|警惕|预防)[^。！？\\n]{0,4}诈骗'
 WHERE rule_id = 'illegal' AND pattern = '诈骗';

