-- ============================================================
-- V31: 用户纪念日（2026-10-06）——「在一起第 N 天」的关系事实
--
-- 为什么放 users 表：这是用户的**关系事实**，复用既有个人资料接口
--   （GET /auth/me、PUT /auth/profile）即可，无需新表/新端点；
--   不引入租户维度（ADR-13：tenant_id 固定 default）。
--
-- anniversary_date 可空：空 = 用户尚未设置，前端首页不展示天数。
--
-- 幂等性：Flyway 按版本号一次性执行（flyway_schema_history 记录），
--   重复启动不会重放本迁移；写法与既有 ALTER 迁移（V19/V25/V28）保持一致。
-- ============================================================

ALTER TABLE users
    ADD COLUMN anniversary_date DATE NULL COMMENT '在一起的纪念日（关系事实；空=未设置，首页不显示天数）';
