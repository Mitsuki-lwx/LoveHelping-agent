-- V36：首次体验引导（onboarding）是否已看过（2026-10-14，ADR-91）
--
-- 背景：产品能力密度高（聊天 / 三牌话术 / 角色模拟屋 / TA 视角 / 旧信存档+情绪轨迹），
--   但新用户没有任何"这里还能做什么"的引导 —— 空态只引导了**聊天**一件事，
--   其余能力全部沉没（用户大概率永远不知道它们存在）。
--
-- 为什么放服务端而不是 localStorage：本产品的数据本来就全在服务端（会话/记忆/档案），
--   引导状态跟着账号走才一致 —— 换设备不该再被引导一次，清缓存也不该又弹一次。
--
-- 默认 0 = 未看过 ⇒ 首次进入聊天页会看到引导卡；关掉即置 1。
ALTER TABLE users ADD COLUMN onboarded TINYINT(1) NOT NULL DEFAULT 0;
